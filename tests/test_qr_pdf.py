"""QR encoder and PDF writer."""

from __future__ import annotations

import io
import re

import pytest

from taskdragon import pdf, qr


def test_qr_structure() -> None:
    matrix = qr.encode("hello")
    assert len(matrix) == 21 and all(len(row) == 21 for row in matrix)
    # Finder patterns in three corners: a dark 7x7 ring with a 3x3 core.
    for x0, y0 in ((0, 0), (14, 0), (0, 14)):
        ring = [matrix[y0][x0 + i] for i in range(7)]
        assert ring == [True] * 7
        assert matrix[y0 + 1][x0 + 1] is False and matrix[y0 + 3][x0 + 3] is True
    rows = qr.encode_rows("https://example.com/taskdragon?maint_task=abc")
    assert set("".join(rows)) <= {"0", "1"} and len(rows) == len(rows[0])
    with pytest.raises(ValueError):
        qr.encode("x" * 3000)


@pytest.mark.parametrize(
    "text",
    [
        "A",
        "https://ha.example.com:8123/taskdragon?maint_task=4f3c2a1b9d8e7f60&do=complete",
        "Ünïcødé ✓ 🔧 " * 12,
        "x" * 600,
    ],
)
def test_qr_decodes(text: str) -> None:
    zxingcpp = pytest.importorskip("zxingcpp")
    image_module = pytest.importorskip("PIL.Image")
    matrix = qr.encode(text)
    scale, border = 4, 4
    size = (len(matrix) + 2 * border) * scale
    image = image_module.new("L", (size, size), 255)
    pixels = image.load()
    for y, row in enumerate(matrix):
        for x, dark in enumerate(row):
            if dark:
                for dy in range(scale):
                    for dx in range(scale):
                        pixels[(x + border) * scale + dx, (y + border) * scale + dy] = 0
    results = zxingcpp.read_barcodes(image)
    assert results and results[0].text == text


def _document(rows: int) -> bytes:
    return pdf.render_table_document(
        title="Service record — Furnace (#3)",
        subtitle_lines=["Carrier 59SC5 · Utility Room", "01/01/2026 – 12/31/2026"],
        columns=[pdf.Column("Date", 70), pdf.Column("Task", 120), pdf.Column("Notes", 236), pdf.Column("Cost", 60, "right")],
        rows=[[f"10/{i % 28 + 1:02d}/2026", f"Replace Filter (#3.1-{i})", "Swapped the 16x25x4 filter (MERV 11). " * (i % 4), "$12.50"] for i in range(rows)],
        footer_line=f"{rows} entries · Total cost: $ {rows * 12.5:.2f}",
        generated_line="Generated by TaskDragon",
    )


def test_pdf_structure_and_xref_offsets() -> None:
    data = _document(5)
    assert data.startswith(b"%PDF-1.4") and data.rstrip().endswith(b"%%EOF")
    startxref = int(re.search(rb"startxref\n(\d+)", data).group(1))
    assert data[startxref : startxref + 4] == b"xref"
    entries = re.findall(rb"(\d{10}) 00000 n ", data)
    for number, offset in enumerate(entries, start=1):
        assert data[int(offset) :].startswith(b"%d 0 obj" % number)
    assert b"(Service record \x97 Furnace \\(#3\\))" in data  # escaped parentheses, WinAnsi em dash


def test_pdf_paginates_and_reads_back() -> None:
    pypdf = pytest.importorskip("pypdf")
    data = _document(120)
    reader = pypdf.PdfReader(io.BytesIO(data))
    assert len(reader.pages) > 2
    first = reader.pages[0].extract_text()
    assert "Service record" in first and "Replace Filter" in first and "Page 1 of" in first
    assert "120 entries" in reader.pages[-1].extract_text()


def test_wrap_breaks_long_words() -> None:
    lines = pdf.wrap("a" * 200, 50, 10)
    assert len(lines) > 3 and all(pdf.text_width(line, 10) <= 50 for line in lines)
    assert pdf.wrap("one two\nthree", 1000, 10) == ["one two", "three"]
